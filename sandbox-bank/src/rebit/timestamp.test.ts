import { describe, expect, it } from 'vitest';

import { parseRebitTimestamp } from './timestamp.ts';

const T = Date.UTC(2026, 8, 26, 10, 0, 0) / 1000; // 2026-09-26T10:00:00Z

describe('parseRebitTimestamp (FORMATS §12)', () => {
  it.each([
    ['2026-09-26T10:00:00.000Z', T],
    ['2026-09-26T10:00:00Z', T],
    ['2026-09-26T10:00:00', T],
    ['2026-09-26T15:30:00+05:30', T],
    ['2026-09-26T15:30:00+0530', T],
    ['2026-09-26T10:00:00.059+0000', T],
    ['2026-09-26T04:30:00-05:30', T],
    ['2026-09-26T10:00:00.123456789Z', T],
    ['2028-02-29T00:00:00Z', Date.UTC(2028, 1, 29) / 1000],
    ['2028-02-29T05:30:00+05:30', Date.UTC(2028, 1, 29) / 1000],
  ])('accepts %s', (value, expected) => {
    expect(parseRebitTimestamp(value)).toBe(expected);
  });

  it.each([
    '2026-09-26',
    'yesterday',
    '',
    '2026-02-30T00:00:00Z',
    '2026-02-30T00:00:00+05:30',
    '2026-02-29T00:00:00+0000',
    '2026-02-29T00:00:00',
    '2026-13-01T00:00:00Z',
    '2026-09-26T24:00:00Z',
    '2026-09-26T10:60:00Z',
    '2026-09-26T10:00:60Z',
    '2026-09-26T10:00:00+24:00',
    '2026-09-26T10:00:00.1234567890Z',
    '2026-09-26t10:00:00z',
    '2026-09-26 10:00:00Z',
    ' 2026-09-26T10:00:00Z',
  ])('rejects %j', (value) => {
    expect(parseRebitTimestamp(value)).toBeUndefined();
  });
});
